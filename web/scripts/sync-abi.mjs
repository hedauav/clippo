// Regenerates src/lib/chain/escrow-abi.ts from ../contracts/abi/ClippoEscrow.json (typed `as const` ABI for viem).
// Run: npm run abi:sync   (after `forge inspect ClippoEscrow abi --json > contracts/abi/ClippoEscrow.json`)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.dirname(fileURLToPath(import.meta.url));
const abi = JSON.parse(readFileSync(path.join(root, "../../contracts/abi/ClippoEscrow.json"), "utf8"));
const out = `// GENERATED by scripts/sync-abi.mjs from contracts/abi/ClippoEscrow.json. Do not edit by hand.
export const escrowAbi = ${JSON.stringify(abi, null, 2)} as const;
`;
writeFileSync(path.join(root, "../src/lib/chain/escrow-abi.ts"), out);
console.log(`wrote escrow-abi.ts (${abi.length} entries)`);
